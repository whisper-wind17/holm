"""Password, session-token and CSRF-token primitives.

This package owns the cryptographic side of local accounts. It knows nothing
about HTTP, cookies or the database: the login flow, cookie attributes, CSRF
enforcement and lockout belong to the Control API, and the tables are
``packages/persistence``. Everything here takes a value in and returns a value
out, which is what makes it testable without a server or a cluster.
"""

